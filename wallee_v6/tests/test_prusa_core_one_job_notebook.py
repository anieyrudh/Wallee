def test_load_persisted_notebook_rejects_stale_schema(tmp_path):
    notebook = build_job_notebook(
        printable=PrintableFile(path="/usb/PRINTS/DEMO.GCODE", display_name="demo.gcode"),
        file_info=None,
        file_text=_SAMPLE_GCODE,
    )
    assert notebook is not None
    path = tmp_path / f"{notebook.job_hash}.notebook.json"
    payload = notebook_to_jsonable(notebook)
    payload.pop("schema_version")
    path.write_text(json.dumps(payload), encoding="utf-8")

    try:
        load_persisted_notebook(path)
    except ValueError as exc:
        assert "keys mismatch" in str(exc)
    else:  # pragma: no cover
        raise AssertionError("expected stale notebook schema to be rejected")


def test_persisted_notebook_round_trips_current_schema(tmp_path):
    notebook = build_job_notebook(
        printable=PrintableFile(path="/usb/PRINTS/DEMO.GCODE", display_name="demo.gcode"),
        file_info=None,
        file_text=_SAMPLE_GCODE,
    )
    assert notebook is not None
    path = tmp_path / f"{notebook.job_hash}.notebook.json"
    persist_job_notebook(path, notebook)

    loaded = load_persisted_notebook(path)

    assert loaded.job_hash == notebook.job_hash
    assert [section.section_id for section in loaded.sections] == [section.section_id for section in notebook.sections]
    assert [section.progress_start_pct for section in loaded.sections] == [
        section.progress_start_pct for section in notebook.sections
    ]
    assert [section.progress_end_pct for section in loaded.sections] == [
        section.progress_end_pct for section in notebook.sections
    ]
    assert loaded.active_section(90.0).section_id == notebook.active_section(90.0).section_id
    assert [note.note_id for note in loaded.global_notes] == [note.note_id for note in notebook.global_notes]
    assert loaded.parser_version == CURRENT_NOTEBOOK_PARSER_VERSION


def test_load_persisted_notebook_accepts_legacy_section_payload_without_progress_windows(tmp_path):
    notebook = build_job_notebook(
        printable=PrintableFile(path="/usb/PRINTS/DEMO.GCODE", display_name="demo.gcode"),
        file_info=None,
        file_text=_SAMPLE_GCODE,
    )
    assert notebook is not None
    path = tmp_path / f"{notebook.job_hash}.notebook.json"
    payload = notebook_to_jsonable(notebook)
    payload["schema_version"] = "1.2"
    for section in payload["sections"]:
        section.pop("progress_start_pct")
        section.pop("progress_end_pct")
    path.write_text(json.dumps(payload), encoding="utf-8")

    loaded = load_persisted_notebook(path)

    assert loaded.job_hash == notebook.job_hash
    assert all(section.progress_start_pct == 0.0 for section in loaded.sections)
    assert all(section.progress_end_pct == 100.0 for section in loaded.sections)


