def test_gcode_planning_facts_are_derived_and_exposed_in_active_payload():
    notebook = build_job_notebook(
        printable=PrintableFile(path="/usb/PRINTS/STRINGING_FACTS.GCODE", display_name="stringing_facts.gcode"),
        file_info=None,
        file_text=_PLANNING_FACTS_GCODE,
    )
    assert notebook is not None
    assert notebook.baselines.estimated_print_time_s == 600.0
    assert len(notebook.sections) == 3

    active_section = notebook.sections[1]
    facts = active_section.gcode_facts
    assert facts.long_travel_count >= 2
    assert facts.long_travel_distance_mm > 90.0
    assert facts.retraction_count == 1
    assert facts.restart_count == 1
    assert facts.travel_to_extrusion_ratio is not None
    assert facts.travel_to_extrusion_ratio > 10.0
    assert facts.active_m204_p_mm_s2 == 800.0
    assert facts.active_m204_t_mm_s2 == 1500.0
    assert facts.active_m204_r_mm_s2 == 300.0
    assert facts.extrusion_cluster_count >= 2
    assert any("long_travel" in window.reason_tags for window in facts.snapshot_windows)
    assert all(window.gcode_line_start is not None for window in facts.snapshot_windows)
    assert "stringing_test_geometry" in active_section.tags

    progress = (active_section.progress_start_pct + active_section.progress_end_pct) / 2.0
    active = notebook.select_active_notes(progress, lifecycle="PRINTING", job_active=True)
    active_payload = active_notes_to_jsonable(active)
    planner_facts = active_payload["planner_facts"]
    assert planner_facts["geometry"]["repeated_tower_or_stringing_test"] is True
    assert active_section.section_id in planner_facts["geometry"]["section_ids"]
    assert planner_facts["active_section"]["section_id"] == active_section.section_id
    assert planner_facts["active_section"]["remaining_progress_pct"] > 0
    assert planner_facts["active_section"]["remaining_time_s"] > 0
    assert planner_facts["active_section"]["gcode_facts"]["retraction_count"] == 1
    assert any(note["note_id"] == "global_stringing_geometry" for note in active_payload["global_notes"])


