def test_job_hash_is_stable_for_same_file_and_ignores_transient_input_availability():
    printable = PrintableFile(
        path="/usb/PRINTS/BENCHY~2.BGC",
        display_name="Benchy_Rules_0.4n_0.2mm_PLA_COREONE_14m.bgcode",
        size_bytes=123456,
        modified_ts=1711800000,
    )
    text = _fixture_text("sample_prusa.gcode")
    with_text = build_job_notebook(
        printable=printable,
        file_info={"metadata": {"filament_type": "PLA", "layer_height": 0.2}},
        file_text=text,
    )
    without_text = build_job_notebook(
        printable=printable,
        file_info={"metadata": {"filament_type": "PLA", "layer_height": 0.2}},
        file_text=None,
    )
    repeated = build_job_notebook(
        printable=printable,
        file_info={"metadata": {"filament_type": "PLA", "layer_height": 0.2}},
        file_text=text,
    )

    assert with_text is not None
    assert without_text is not None
    assert repeated is not None
    assert with_text.job_hash == without_text.job_hash == repeated.job_hash


