def test_benchy_golden_grounding_has_sections_and_nonempty_active_notes():
    real_text = normalize_prusa_print_text(
        file_path="/usb/BENCHY~2.BGC",
        raw_bytes=_bgcode_fixture_bytes("benchy_rules_real.bgcode"),
    )
    notebook = build_job_notebook(
        printable=PrintableFile(
            path="/usb/PRINTS/BENCHY~2.BGC",
            display_name="Benchy_Rules_0.4n_0.2mm_PLA_COREONE_14m.bgcode",
            size_bytes=len(_bgcode_fixture_bytes("benchy_rules_real.bgcode")),
        ),
        file_info=None,
        file_text=real_text,
    )
    assert notebook is not None

    section_ids = {section.section_id for section in notebook.sections}
    assert len(notebook.sections) >= 3
    assert notebook.global_notes
    assert notebook.local_notes
    assert all(not note.section_ids for note in notebook.global_notes)
    assert all(set(note.section_ids).issubset(section_ids) for note in notebook.local_notes)

    active = notebook.select_active_notes(50.0, lifecycle="PRINTING", job_active=True)
    assert active.selection_context.current_section_ids
    assert active.global_notes or active.local_notes
    assert any("bridge" in note.reason_tags or "high_flow" in note.reason_tags for note in active.global_notes + active.local_notes)
    assert notebook.source_text_grounded_internal is True


