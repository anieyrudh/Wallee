def _fixture_text(name: str) -> str:
    repo_root = Path(__file__).resolve().parents[1]
    candidates = [
        repo_root / "tests" / "fixtures" / name,
        repo_root.parent / "wallee_v6_fff_prusa_addon" / "tests" / "fixtures" / name,
    ]
    for candidate in candidates:
        if candidate.exists():
            return candidate.read_text(encoding="utf-8", errors="replace")
    raise FileNotFoundError(f"fixture not found: {name}")


def _bgcode_fixture_bytes(name: str) -> bytes:
    base = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "prusa_bgcode"
    return (base / name).read_bytes()


def test_build_job_notebook_creates_grounded_sections_and_notes(tmp_path):
    notes_path = tmp_path / "notes"
    printable = PrintableFile(path="/usb/PRINTS/DEMO.GCODE", display_name="demo.gcode", size_bytes=len(_SAMPLE_GCODE))
    baseline = build_job_notebook(
        printable=printable,
        file_info={"metadata": {"filament_type": "PLA", "layer_height": 0.2, "bed_temperature": 60}},
        file_text=_SAMPLE_GCODE,
    )
    assert baseline is not None

    (notes_path / f"{baseline.job_hash}.notes.json").parent.mkdir(parents=True, exist_ok=True)
    (notes_path / f"{baseline.job_hash}.notes.json").write_text(
        json.dumps(
            {
                "global_notes": [
                    {
                        "note_id": "global_operator",
                        "scope": "global",
                        "kind": "watchpoint",
                        "text": "Operator note: watch the bridge region after 60% progress.",
                        "priority": 15,
                    }
                ],
                "local_notes": [
                    {
                        "note_id": "local_bridge_focus",
                        "scope": "local",
                        "kind": "watchpoint",
                        "text": "Bridge focus region.",
                        "section_ids": ["sec_0003"],
                        "priority": 35,
                    }
                ],
            }
        ),
        encoding="utf-8",
    )

    notebook = build_job_notebook(
        printable=printable,
        file_info={"metadata": {"filament_type": "PLA", "layer_height": 0.2, "bed_temperature": 60}},
        file_text=_SAMPLE_GCODE,
        notes_dir=notes_path,
    )
    assert notebook is not None
    assert notebook.material == "PLA"
    assert notebook.nozzle_target_c == 215
    assert notebook.bed_target_c == 60
    assert len(notebook.sections) == 3
    assert notebook.sections[0].layer_start == 0
    assert notebook.sections[2].layer_start == 2
    assert notebook.sections[2].z_min_mm == 0.6
    assert notebook.active_section(90.0).section_id == "sec_0003"

    active_notes = notebook.active_notes(90.0)
    texts = [note.text for note in active_notes]
    assert any("Operator note" in text for text in texts)
    assert any("Bridge focus region" in text for text in texts)
    assert any("Bridge-heavy region" in text for text in texts)

    payload = notebook_to_jsonable(notebook)
    assert sorted(payload.keys()) == [
        "baselines",
        "build",
        "global_notes",
        "job",
        "local_notes",
        "notebook_id",
        "printer_family",
        "schema_version",
        "sections",
    ]
    assert payload["schema_version"] == CURRENT_NOTEBOOK_SCHEMA_VERSION
    assert payload["printer_family"] == "prusa_core_one_plus"
    assert payload["job"]["job_hash"] == notebook.job_hash
    assert payload["baselines"]["speed_pct_default"] == 100.0
    assert all(note["section_ids"] == [] for note in payload["global_notes"])
    assert all(note["section_ids"] for note in payload["local_notes"])
    assert payload["sections"][2]["section_id"] == "sec_0003"
    assert payload["sections"][2]["progress_start_pct"] > payload["sections"][1]["progress_start_pct"]
    assert payload["sections"][2]["progress_end_pct"] == 100.0
    assert payload["local_notes"][-1]["note_id"] == "local_bridge_focus"

    active = notebook.select_active_notes(90.0, lifecycle="PRINTING", job_active=True)
    active_payload = active_notes_to_jsonable(active)
    assert active_payload["schema_version"] == "1.0"
    assert len(active_payload["global_notes"]) <= 4
    assert len(active_payload["local_notes"]) <= 6
    assert set(active_payload["family_hints"].keys()) == {
        "speed",
        "flow",
        "nozzle",
        "bed",
        "pressure_advance",
        "accel",
    }


